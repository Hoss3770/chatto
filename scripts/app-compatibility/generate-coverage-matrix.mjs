/** Generate the exhaustive Phase 0 coverage matrix from spec/registry. */

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { mkdir } from 'node:fs/promises';

function parseArguments(argv) {
  const options = {
    registryDir: 'spec/registry',
    output: 'docs/compat/coverage-matrix.md'
  };
  for (let index = 0; index < argv.length; index += 1) {
    if (argv[index] === '--registry-dir') options.registryDir = argv[++index];
    else if (argv[index] === '--output') options.output = argv[++index];
    else throw new Error(`Unknown argument: ${argv[index]}`);
  }
  return options;
}

async function readJson(path) {
  return JSON.parse(await readFile(path, 'utf8'));
}

function cell(value) {
  if (value === null || value === undefined || value === '') return '—';
  return String(value).replaceAll('|', '\\|').replaceAll('\n', ' ');
}

function phase(value) {
  return value === null || value === undefined ? 'Not planned' : `Phase ${value}`;
}

function coverageTable(items, nameOf, noteOf = () => '') {
  const lines = [
    '| Contract | Status | Target | Chatto mapping | Reason | Source note |',
    '| --- | --- | --- | --- | --- | --- |'
  ];
  for (const item of items) {
    const coverage = item.compatibility;
    lines.push(
      `| \`${cell(nameOf(item))}\` | ${cell(coverage.status)} | ${phase(coverage.target_phase)} | ${cell(coverage.semantic_mapping)} | ${cell(coverage.reason)} | ${cell(noteOf(item))} |`
    );
  }
  return ['<!-- prettier-ignore -->', ...lines].join('\n');
}

function countStatuses(items) {
  const counts = { implemented: 0, partial: 0, unsupported: 0 };
  for (const item of items) counts[item.compatibility.status] += 1;
  return counts;
}

function addCounts(left, right) {
  return {
    implemented: left.implemented + right.implemented,
    partial: left.partial + right.partial,
    unsupported: left.unsupported + right.unsupported
  };
}

async function main() {
  const options = parseArguments(process.argv.slice(2));
  const registry = resolve(options.registryDir);
  const [
    summary,
    methods,
    events,
    scopes,
    blocks,
    elements,
    composition,
    manifest,
    surfaces,
    sdk,
    conflicts
  ] = await Promise.all([
    readJson(`${registry}/summary.json`),
    readJson(`${registry}/methods.json`),
    readJson(`${registry}/events.json`),
    readJson(`${registry}/scopes.json`),
    readJson(`${registry}/blocks.json`),
    readJson(`${registry}/elements.json`),
    readJson(`${registry}/composition-objects.json`),
    readJson(`${registry}/manifest-keys.json`),
    readJson(`${registry}/surfaces.json`),
    readJson(`${registry}/sdk-compatibility.json`),
    readJson(`${registry}/source-conflicts.json`)
  ]);

  const groups = [
    ['Methods', methods.methods],
    ['Events', events.events],
    ['Scopes', scopes.scopes],
    ['Blocks', blocks.blocks],
    ['Elements', elements.elements],
    ['Composition objects', composition.composition_objects],
    ['Manifest keys', manifest.manifest_keys],
    [
      'Platform surfaces',
      surfaces.surfaces.map((surface) => ({ ...surface, compatibility: surface }))
    ]
  ];
  const total = groups.reduce((counts, [, items]) => addCounts(counts, countStatuses(items)), {
    implemented: 0,
    partial: 0,
    unsupported: 0
  });

  const lines = [
    '# App Compatibility Coverage Matrix',
    '',
    '> Generated by `scripts/app-compatibility/generate-coverage-matrix.mjs`. Do not edit this file by hand.',
    '',
    `**Baseline:** Phase 0 source snapshot \`${summary.source.documentation.sitemap_sha256.slice(0, 12)}\``,
    '',
    'This matrix measures the target wire contract that an app can use today. A Chatto domain feature does not count as implemented until the compatibility route, authentication, response shape, and conformance test exist. The semantic mapping column records planned reuse; it is not a support claim.',
    '',
    '## Summary',
    '',
    '<!-- prettier-ignore -->',
    '| Status | Count | Meaning |',
    '| --- | ---: | --- |',
    `| implemented | ${total.implemented} | The target contract and its conformance test exist. |`,
    `| partial | ${total.partial} | A compatible subset exists, with a documented gap. |`,
    `| unsupported | ${total.unsupported} | The target contract is not available. |`,
    '',
    `The documentation snapshot contains ${summary.counts.documented_methods} documented methods, ${summary.counts.events} events, ${summary.counts.scopes} scopes, ${summary.counts.blocks} block types, ${summary.counts.elements} element types, ${summary.counts.composition_objects} composition objects, and ${summary.counts.manifest_keys} manifest keys. Published SDK source adds ${summary.counts.sdk_only_methods} method names that do not have a current method page.`,
    '',
    'The only current partial surface is the existing Chatto bot incoming webhook. It accepts compatible text and destination fields, but it is not a complete app installation or structured-message contract. No Web API method, event subscription, app scope, structured block object, or manifest key is implemented through the target wire protocol.',
    '',
    '## SDK source cross-check',
    '',
    '<!-- prettier-ignore -->',
    '| SDK inventory | Method count |',
    '| --- | ---: |',
    ...Object.entries(sdk.method_counts).map(([name, count]) => `| ${name} | ${count} |`),
    '',
    "The counts differ because SDK releases contain different new and legacy surfaces. The method table below uses their case-insensitive union with current documentation and preserves each SDK's exact spelling.",
    '',
    '## Source conflicts',
    '',
    '<!-- prettier-ignore -->',
    '| Topic | Decision | Evidence |',
    '| --- | --- | --- |',
    ...conflicts.conflicts.map(
      (conflict) =>
        `| ${cell(conflict.topic)} | ${cell(conflict.decision)} | ${cell(conflict.evidence)} |`
    ),
    '',
    '## Platform surfaces',
    '',
    coverageTable(
      surfaces.surfaces.map((surface) => ({ ...surface, compatibility: surface })),
      (surface) => surface.name
    ),
    '',
    '## Methods',
    '',
    coverageTable(
      methods.methods,
      (method) => method.name,
      (method) => {
        const sdks = Object.entries(method.sdk_presence)
          .filter(([, present]) => present)
          .map(([name]) => name)
          .join(', ');
        return `${method.documented ? 'documented' : 'SDK only'}${sdks ? `; ${sdks}` : ''}${method.deprecated ? '; deprecated' : ''}`;
      }
    ),
    '',
    '## Events',
    '',
    coverageTable(
      events.events,
      (event) => event.name,
      (event) => event.delivery_apis.join(', ')
    ),
    '',
    '## Scopes',
    '',
    coverageTable(
      scopes.scopes,
      (scope) => scope.name,
      (scope) => {
        const permissions = scope.compatibility.chatto_permissions || [];
        return permissions.length
          ? `Chatto permissions: ${permissions.join(', ')}`
          : scope.token_types.join(', ');
      }
    ),
    '',
    '## Blocks',
    '',
    coverageTable(
      blocks.blocks,
      (block) => block.wire_type,
      (block) =>
        block.source.kind === 'sdk_only' ? 'SDK only' : block.available_in_surfaces.join(', ')
    ),
    '',
    '## Elements',
    '',
    coverageTable(
      elements.elements,
      (element) => element.wire_type,
      (element) =>
        element.source.kind === 'sdk_only' ? 'SDK only' : element.available_in_surfaces.join(', ')
    ),
    '',
    '## Composition objects',
    '',
    coverageTable(composition.composition_objects, (object) => object.wire_type),
    '',
    '## Manifest keys',
    '',
    coverageTable(
      manifest.manifest_keys,
      (key) => key.path,
      (key) => (key.required ? 'required by source schema' : 'optional or conditionally required')
    ),
    '',
    '## Compatibility claim',
    '',
    'Chatto does not yet claim compatibility levels 1–4. Phase 0 defines the contracts and mappings only. Level 5 vendor-hosted Marketplace apps remain out of reach because their vendor-controlled hosts and OAuth registrations target another service. The product must always say this limit directly.',
    ''
  ];

  const output = resolve(options.output);
  await mkdir(dirname(output), { recursive: true });
  await writeFile(output, lines.join('\n'));
  console.log(`Generated ${options.output}`);
}

main().catch((error) => {
  console.error(error.stack || error);
  process.exitCode = 1;
});
