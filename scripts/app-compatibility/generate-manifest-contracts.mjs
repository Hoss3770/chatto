import { spawnSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import process from 'node:process';

const sourcePath = 'spec/registry/manifest-keys.json';
const scopesPath = 'spec/registry/scopes.json';
const outputPath = 'cli/internal/appcompat/manifest_contracts_generated.go';

function goString(value) {
  return JSON.stringify(value ?? '');
}

function goStrings(values = []) {
  if (values.length === 0) return 'nil';
  return `[]string{${values.map(goString).join(', ')}}`;
}

function optionalInteger(value) {
  return Number.isInteger(value) ? String(value) : '-1';
}

function formatGo(source) {
  const result = spawnSync('gofmt', [], {
    input: source,
    encoding: 'utf8',
    maxBuffer: 16 * 1024 * 1024
  });
  if (result.status !== 0) {
    throw new Error(`gofmt failed: ${result.stderr || `exit status ${result.status}`}`);
  }
  return result.stdout;
}

function generate(source, scopes) {
  const lines = [
    '// Code generated by scripts/app-compatibility/generate-manifest-contracts.mjs. DO NOT EDIT.',
    '',
    'package appcompat',
    '',
    'var manifestContracts = []manifestContract{'
  ];
  for (const entry of source.manifest_keys) {
    const constraints = entry.constraints ?? {};
    lines.push(
      '\t{',
      `\t\tPath: ${goString(entry.path)},`,
      `\t\tType: ${goString(entry.type_hint)},`,
      `\t\tRequired: ${entry.required === true},`,
      `\t\tRequirement: ${goString(entry.requirement)},`,
      `\t\tAllowedLiterals: ${goStrings(entry.allowed_literals)},`,
      `\t\tMinLength: ${optionalInteger(constraints.min_length)},`,
      `\t\tMaxLength: ${optionalInteger(constraints.max_length)},`,
      `\t\tMinItems: ${optionalInteger(constraints.min_items)},`,
      `\t\tMaxItems: ${optionalInteger(constraints.max_items)},`,
      `\t\tMinKeyLength: ${optionalInteger(constraints.min_key_length)},`,
      `\t\tMaxKeyLength: ${optionalInteger(constraints.max_key_length)},`,
      `\t\tMaxItemLength: ${optionalInteger(constraints.max_item_length)},`,
      `\t\tStatus: ${goString(entry.compatibility?.status)},`,
      `\t\tReason: ${goString(entry.compatibility?.reason)},`,
      '\t},'
    );
  }
  lines.push('}', '', 'var knownAppScopes = map[string]struct{}{');
  for (const entry of [...scopes.scopes].sort((a, b) => a.name.localeCompare(b.name))) {
    lines.push(`\t${goString(entry.name)}: {},`);
  }
  lines.push('}', '');
  return lines.join('\n');
}

const [source, scopes] = await Promise.all([
  readFile(sourcePath, 'utf8').then(JSON.parse),
  readFile(scopesPath, 'utf8').then(JSON.parse)
]);
const generated = formatGo(generate(source, scopes));
if (process.argv.includes('--check')) {
  const current = await readFile(outputPath, 'utf8').catch(() => '');
  if (current !== generated) {
    console.error(`${outputPath} is stale; run pnpm app-compat:generate-manifest-contracts`);
    process.exitCode = 1;
  }
} else {
  await writeFile(outputPath, generated);
}
